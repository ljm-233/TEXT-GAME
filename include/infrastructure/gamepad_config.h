#pragma once

// ============================================================
// 手柄手感参数集中配置
//
// 修改这些值即可调整手柄手感，无需改动其他文件。
// 每个参数后面标了"更灵敏" / "更不灵敏" 的方向。
// ============================================================

namespace GamepadConfig {

// ===== 摇杆死区 =====
// 原始摇杆值的死区（0.0~1.0）
// 越大 = 越不灵敏（需要推更多才有效）
// 建议范围：0.15 ~ 0.35
constexpr float kStickDeadzone = 0.25f;

// ===== 焦点导航（设置页 / 菜单）=====
// 摇杆用于焦点导航的阈值（经过死区重映射后）
// 越大 = 越难触发（越稳定，越不容易误触）
// 越小 = 越容易触发（越灵敏）
// 建议范围：0.4 ~ 0.7
constexpr float kNavStickThreshold = 0.5f;

// 首次触发后，多久开始重复（秒）
// 越大 = 重复前停留越久（越不容易连跳）
// 越小 = 更快进入连续移动
// 建议范围：0.20 ~ 0.50
constexpr float kNavInitialDelay = 0.35f;

// 重复间隔（秒）
// 越大 = 重复越慢
// 越小 = 重复越快
// 建议范围：0.06 ~ 0.15
constexpr float kNavRepeatEvery = 0.10f;

// ===== 玩家移动（游戏内）=====
// 摇杆用于玩家移动的阈值（经过死区重映射后）
// 越大 = 需要推更多才移动
// 越小 = 轻推就能移动
// 建议范围：0.25 ~ 0.45
constexpr float kMoveStickThreshold = 0.30f;

} // namespace GamepadConfig